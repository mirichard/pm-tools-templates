const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
const base=process.env.UAT_BASE_URL || 'http://127.0.0.1:3101';
const evidence=process.env.UAT_EVIDENCE || '/tmp';
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1024,height:900}});
 page.setDefaultTimeout(15000);
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(`${base}/recovery-uat/uat/`);
 await page.getByRole('button',{name:'Request insights',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Request completed'));
 assert.match(await page.locator('#results').innerText(),/not assessed/);
 await page.getByRole('button',{name:'Load synthetic shortfall'}).click();
 await page.getByRole('button',{name:'Request insights',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Request completed'));
 assert.match(await page.locator('#results').innerText(),/Shortfall \(person-hours\): 40/);
 await page.screenshot({path:path.join(evidence,'recovery-uat-desktop.png'),fullPage:true});
 await page.route('**/api/v1/insights/analyze',route=>route.fulfill({status:500,contentType:'application/json',body:'{"error":"Synthetic service failure"}'}));
 await page.getByRole('button',{name:'Request insights',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Request failed'));
 assert.equal(await page.locator('#results').isVisible(),false);
 await page.unroute('**/api/v1/insights/analyze');
 await page.getByRole('button',{name:'Request insights',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Request completed'));
 await page.goto(`${base}/recovery-uat/uat/?fixture=missing-quality`);
 assert.match(await page.locator('#fixture-notice').innerText(),/intentionally omits the Quality section/);
 const partialResponse = page.waitForResponse(response=>response.url().endsWith('/recovery-uat/missing-quality/insights/analyze'));
 await page.getByRole('button',{name:'Request insights',exact:true}).click();
 const partial = await (await partialResponse).json();
 assert.equal(Object.hasOwn(partial.data,'qualityPrediction'),false);
 await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Request completed'));
 const quality = page.locator('article').filter({has:page.getByRole('heading',{name:'Quality — simulated',exact:true})});
 assert.equal(await quality.locator('p').innerText(),'Unavailable');
 for (const label of ['Resources','Schedule']) {
  const card = page.locator('article').filter({has:page.getByRole('heading',{name:`${label} — simulated`,exact:true})});
  assert.match(await card.innerText(),/Simulated output received/);
 }
 assert.match(await page.locator('#results').innerText(),/Estimated benefit: unavailable/);
 await page.screenshot({path:path.join(evidence,'recovery-uat-missing-quality.png'),fullPage:true});
 await page.goto(`${base}/recovery-uat/uat/`);
 await page.getByRole('button',{name:'Request insights',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Request completed'));
 assert.match(await page.locator('article').filter({has:page.getByRole('heading',{name:'Quality — simulated',exact:true})}).innerText(),/Simulated output received/);
 await page.reload();assert.equal(await page.locator('#results').isVisible(),false);
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.screenshot({path:path.join(evidence,'recovery-uat-mobile.png'),fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('PASS: rendered baseline, evidenced shortfall, simulated failure, retry, missing Quality API section unavailable, normal Quality restored, reload clears history, narrow layout, no browser errors');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
